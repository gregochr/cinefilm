CREATE TABLE film_collection (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tmdb_id BIGINT,
    name VARCHAR(255) NOT NULL,
    poster_path VARCHAR(255)
);

CREATE TABLE collection_part (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id BIGINT NOT NULL REFERENCES film_collection (id),
    tmdb_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    release_year INTEGER,
    release_order INTEGER NOT NULL,
    poster_path VARCHAR(255)
);

CREATE TABLE film (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tmdb_id BIGINT,
    title VARCHAR(255) NOT NULL,
    sort_title VARCHAR(255) NOT NULL,
    release_year INTEGER NOT NULL,
    overview VARCHAR(4000),
    poster_path VARCHAR(255),
    backdrop_path VARCHAR(255),
    added_at TIMESTAMP WITH TIME ZONE NOT NULL,
    collection_id BIGINT REFERENCES film_collection (id)
);

CREATE TABLE film_genre (
    film_id BIGINT NOT NULL REFERENCES film (id),
    genre VARCHAR(100) NOT NULL,
    PRIMARY KEY (film_id, genre)
);

CREATE TABLE edition (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    film_id BIGINT NOT NULL REFERENCES film (id),
    name VARCHAR(255) NOT NULL,
    release_year INTEGER,
    runtime_ms BIGINT NOT NULL,
    note VARCHAR(500),
    credits_marker_ms BIGINT
);

CREATE TABLE media_file (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edition_id BIGINT NOT NULL REFERENCES edition (id),
    path VARCHAR(2000) NOT NULL,
    kind VARCHAR(20) NOT NULL,
    container VARCHAR(20),
    video_codec VARCHAR(40),
    width INTEGER,
    height INTEGER,
    bitrate BIGINT,
    size_bytes BIGINT,
    duration_ms BIGINT,
    sprite_ready BOOLEAN NOT NULL DEFAULT FALSE,
    added_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE audio_stream (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_file_id BIGINT NOT NULL REFERENCES media_file (id),
    idx INTEGER NOT NULL,
    language VARCHAR(40),
    channels VARCHAR(20),
    codec VARCHAR(40),
    title VARCHAR(255),
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    safari_playable BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE subtitle_stream (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_file_id BIGINT NOT NULL REFERENCES media_file (id),
    idx INTEGER NOT NULL,
    language VARCHAR(40),
    forced BOOLEAN NOT NULL DEFAULT FALSE,
    title VARCHAR(255),
    format VARCHAR(40)
);

CREATE TABLE person (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tmdb_id BIGINT,
    name VARCHAR(255) NOT NULL,
    profile_path VARCHAR(255)
);

CREATE TABLE credit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    film_id BIGINT NOT NULL REFERENCES film (id),
    person_id BIGINT NOT NULL REFERENCES person (id),
    role VARCHAR(20) NOT NULL,
    character_name VARCHAR(255),
    ord INTEGER NOT NULL
);

CREATE TABLE playback_state (
    edition_id BIGINT PRIMARY KEY REFERENCES edition (id),
    position_ms BIGINT NOT NULL,
    watched BOOLEAN NOT NULL,
    watched_at TIMESTAMP WITH TIME ZONE,
    last_played_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE film_preference (
    film_id BIGINT PRIMARY KEY REFERENCES film (id),
    default_edition_id BIGINT,
    last_edition_id BIGINT,
    quality VARCHAR(20),
    audio_stream_id BIGINT,
    subtitle VARCHAR(40)
);

CREATE INDEX idx_film_collection ON film (collection_id);
CREATE INDEX idx_edition_film ON edition (film_id);
CREATE INDEX idx_media_file_edition ON media_file (edition_id);
CREATE INDEX idx_audio_media_file ON audio_stream (media_file_id);
CREATE INDEX idx_subtitle_media_file ON subtitle_stream (media_file_id);
CREATE INDEX idx_credit_film ON credit (film_id);
CREATE INDEX idx_credit_person ON credit (person_id);
CREATE INDEX idx_part_collection ON collection_part (collection_id);
