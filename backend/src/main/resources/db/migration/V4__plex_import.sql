-- Plex import (expand-only): one row per import run; the report is the JSON the Admin panel shows (lists capped at 200).
CREATE TABLE plex_import_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE,
    report TEXT,
    error VARCHAR(500)
);
