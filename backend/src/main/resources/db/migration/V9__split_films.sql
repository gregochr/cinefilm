-- Split films (pt1/pt2), self-grouping editions: expand-only. A media file knows which part of its edition it is
-- (1 for every existing file); a film the owner settled is flagged so the scan leaves its grouping alone; an edition
-- records who grouped its files (AUTO by the scan, PLEX by the import, OWNER by hand); a film remembers whether the
-- owner chose its default edition; and every split, join or flag the scan makes is logged.
ALTER TABLE media_file ADD COLUMN part_number INTEGER NOT NULL DEFAULT 1;
CREATE INDEX idx_media_file_edition_kind_part ON media_file (edition_id, kind, part_number);

ALTER TABLE film ADD COLUMN editions_confirmed BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE edition ADD COLUMN grouping_source VARCHAR(10) NOT NULL DEFAULT 'AUTO';

ALTER TABLE film_preference ADD COLUMN default_edition_chosen BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE grouping_change (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    happened_at TIMESTAMP WITH TIME ZONE NOT NULL,
    kind VARCHAR(10) NOT NULL,
    summary VARCHAR(500) NOT NULL
);
