-- Downloading forced subtitles from OpenSubtitles, and playing only proven ones (expand-only: new columns with
-- defaults, two new tables; nothing is dropped or rewritten).
--
-- subtitle_sidecar gains a download as a second kind of row. origin is FILE (a .srt found beside the film, every row
-- so far) or OPENSUBTITLES (a download for an edition). A download keeps its cues here like a file does, so precedence,
-- the served version, the checks and the timing fit work on it unchanged. It is stored against the edition's part 1 as a
-- whole-edition file, with a made-up path (opensubtitles:<edition id>:<file id>) so the unique path still holds, and the
-- scan never touches it. opensubtitles_file_id is the file id /download took, release its release name, imdb_id the IMDb
-- id it was fetched for (downloads for an old id are removed when the film's id changes), downloaded_at when.
ALTER TABLE subtitle_sidecar ADD COLUMN origin VARCHAR(20) NOT NULL DEFAULT 'FILE';
ALTER TABLE subtitle_sidecar ADD COLUMN opensubtitles_file_id BIGINT;
ALTER TABLE subtitle_sidecar ADD COLUMN release VARCHAR(200);
ALTER TABLE subtitle_sidecar ADD COLUMN imdb_id VARCHAR(16);
ALTER TABLE subtitle_sidecar ADD COLUMN downloaded_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE subtitle_sidecar ADD CONSTRAINT subtitle_sidecar_origin_ck
    CHECK (origin IN ('FILE', 'OPENSUBTITLES') AND (origin = 'FILE' OR opensubtitles_file_id IS NOT NULL));

-- forced_download_check: the result of comparing a downloaded subtitle with a different OpenSubtitles file (the proof
-- used when its timing cannot be fitted to the film's own English track). Same columns as forced_subtitle_check, but one
-- row per download (not per edition: the owner's file and a download are each checked on their own), removed with it.
CREATE TABLE forced_download_check (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sidecar_id BIGINT NOT NULL UNIQUE REFERENCES subtitle_sidecar (id) ON DELETE CASCADE,
    served_version VARCHAR(1000) NOT NULL,
    reference_id BIGINT NOT NULL REFERENCES opensubtitles_reference (id) ON DELETE CASCADE,
    verdict VARCHAR(10) NOT NULL,
    matched_share DOUBLE PRECISION NOT NULL,
    served_count INTEGER NOT NULL,
    reference_count INTEGER NOT NULL,
    best_offset_ms INTEGER NOT NULL,
    reasons VARCHAR(1000) NOT NULL,
    checked_at TIMESTAMP WITH TIME ZONE NOT NULL,
    best_file_id BIGINT,
    cut_tags VARCHAR(100) NOT NULL DEFAULT '',
    rules_version INTEGER NOT NULL DEFAULT 2
);
CREATE INDEX forced_download_check_reference_idx ON forced_download_check (reference_id);

-- forced_download_block: an OpenSubtitles file the owner removed from an edition. It is never downloaded or promoted for
-- that edition and IMDb id again. Kept until the edition goes.
CREATE TABLE forced_download_block (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edition_id BIGINT NOT NULL REFERENCES edition (id) ON DELETE CASCADE,
    imdb_id VARCHAR(16) NOT NULL,
    os_file_id BIGINT NOT NULL,
    removed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT forced_download_block_uq UNIQUE (edition_id, imdb_id, os_file_id)
);
