-- Playback health (expand-only: one new table). One row per viewing (one mount of the player on one edition): the
-- browser's own measurements of how the film played (stalls, start-up time, download speeds, quality steps), sent
-- as the viewing goes on and replaced by each newer report. Read in Admin to see how playback behaves at home and
-- away.
-- summary holds the report as JSON text, the server's own serialisation; VARCHAR (not TEXT) so Hibernate's schema
-- validation matches on PostgreSQL and on H2, and so a new figure needs no migration.
-- There is deliberately no foreign key to edition: regrouping deletes editions in bulk, and a cascade would delete the
-- record of a viewing because the library was regrouped. film_id and film_title are copied at the first report.
-- seq rises with every report of a viewing; a report only replaces the stored one when its seq is higher.
CREATE TABLE playback_health (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playback_id VARCHAR(36) NOT NULL UNIQUE,
    edition_id BIGINT NOT NULL,
    film_id BIGINT NOT NULL,
    film_title VARCHAR(255) NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    seq INTEGER NOT NULL,
    summary VARCHAR(16000) NOT NULL
);
CREATE INDEX playback_health_updated_at_idx ON playback_health (updated_at);
