-- Making the OpenSubtitles cross-check robust against bad reference files (expand-only: two columns, one table).
--
-- film.os_candidates: the single-file OpenSubtitles results the checker may compare with, as a JSON array in the
-- search's ranked order (the top three, plus the best result for each cut tag such as Extended or Theatrical, at most
-- eight; each element is the same JSON as os_best). '[]' = searched, none usable; null = stored before this column
-- existed (the search is due again for those films, first). A change of the film's IMDb id resets it to null with
-- os_best.
ALTER TABLE film ADD COLUMN os_candidates TEXT;

-- forced_subtitle_check.rules_version: which version of the comparison rules produced the row. A row made by older rules
-- is stale and is made again (against stored references where possible). Rows made by phase 2d are version 1.
ALTER TABLE forced_subtitle_check ADD COLUMN rules_version INTEGER NOT NULL DEFAULT 1;
-- forced_subtitle_check.best_file_id: the file id of the film's best OpenSubtitles result when the check was made (the
-- reference may be another candidate, so it can no longer stand for it); a check goes stale when the best file changes.
-- Null for rows made by phase 2d, which always used the best file.
ALTER TABLE forced_subtitle_check ADD COLUMN best_file_id BIGINT;

-- forced_check_candidate: the OpenSubtitles files an edition has been compared with, per IMDb id: the ledger of the
-- cap of three candidates per edition and IMDb id, ever. A row is added once a candidate's reference is in hand
-- (downloaded, or already stored) and is never removed, except with its edition. Seeded from the checks already made.
CREATE TABLE forced_check_candidate (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edition_id BIGINT NOT NULL REFERENCES edition (id) ON DELETE CASCADE,
    imdb_id VARCHAR(16) NOT NULL,
    os_file_id BIGINT NOT NULL,
    tried_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT forced_check_candidate_uq UNIQUE (edition_id, imdb_id, os_file_id)
);

INSERT INTO forced_check_candidate (edition_id, imdb_id, os_file_id, tried_at)
SELECT c.edition_id, r.imdb_id, r.os_file_id, c.checked_at
FROM forced_subtitle_check c
JOIN opensubtitles_reference r ON r.id = c.reference_id;
