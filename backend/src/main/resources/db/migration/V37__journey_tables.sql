-- The tables for a train journey's data (expand-only: six new tables; plan: docs/engineering/journey-data-plan.md,
-- decision 3).
--
-- On train journeys the owner's logger records the train's own feed (position, modems, passengers online) and the
-- laptop's state every 30 seconds, beside a film playing. These tables hold those logs in Boyce-Codd normal form.
--
-- device: a kind of laptop (model, CPU, cores, threads, memory), stored once however many journeys it logged.
-- journey: one stretch (segment) of one logger run, on one train unit; run_started_ms and segment are unique.
-- journey_sample: one round of the logger (every 30 s); a round that failed holds only its number and time.
-- journey_modem: a modem the train's router reported during a journey; journey_modem_sample: its state in a round.
-- journey_playback: which playback records (viewings) were watched during a journey. It is a table of its own, not a
-- column on playback_health, and its playback_health_id cascades on delete: that table is capped
-- (PlaybackHealthService.MAX_ROWS) and the cap deletes the oldest rows in bulk (deleteAllByIdInBatch), which a plain
-- foreign key would refuse, and every new viewing after that would fail. Deleting a record takes only its links.
CREATE TABLE device (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model VARCHAR(100) NOT NULL,
    cpu VARCHAR(100) NOT NULL,
    cores INTEGER NOT NULL,
    threads INTEGER NOT NULL,
    memory_bytes BIGINT NOT NULL,
    CONSTRAINT device_kind_unique UNIQUE (model, cpu, cores, threads, memory_bytes)
);

CREATE TABLE journey (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_started_ms BIGINT NOT NULL,
    segment INTEGER NOT NULL,
    device_id BIGINT REFERENCES device (id),
    os_version VARCHAR(40),
    travel_class VARCHAR(10),
    train_unit VARCHAR(100),
    source_file VARCHAR(200),
    logger_version INTEGER NOT NULL,
    imported_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT journey_run_segment_unique UNIQUE (run_started_ms, segment),
    CONSTRAINT journey_travel_class_check CHECK (travel_class IN ('standard', 'first'))
);

CREATE TABLE journey_sample (
    journey_id BIGINT NOT NULL REFERENCES journey (id) ON DELETE CASCADE,
    round_no INTEGER NOT NULL,
    sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    feed_at TIMESTAMP WITH TIME ZONE,
    fix_mode INTEGER,
    fix_age_s INTEGER,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    altitude_m DOUBLE PRECISION,
    speed_mps DOUBLE PRECISION,
    course_deg DOUBLE PRECISION,
    satellites INTEGER,
    online INTEGER,
    users_online INTEGER,
    users_total INTEGER,
    down_limit BIGINT,
    up_limit BIGINT,
    cap_level INTEGER,
    user_class INTEGER,
    data_down_used BIGINT,
    data_up_used BIGINT,
    probe_ms INTEGER,
    probe_code INTEGER,
    power_source VARCHAR(10),
    battery_percent INTEGER,
    low_power INTEGER,
    cpu_limit INTEGER,
    load_avg DOUBLE PRECISION,
    swap_mb DOUBLE PRECISION,
    wifi_rssi INTEGER,
    wifi_noise INTEGER,
    wifi_rate DOUBLE PRECISION,
    wifi_phy INTEGER,
    wifi_channel INTEGER,
    wifi_band INTEGER,
    wifi_width INTEGER,
    PRIMARY KEY (journey_id, round_no)
);

CREATE TABLE journey_modem (
    journey_id BIGINT NOT NULL REFERENCES journey (id) ON DELETE CASCADE,
    modem_index INTEGER NOT NULL,
    device_type VARCHAR(40),
    device_subtype VARCHAR(40),
    PRIMARY KEY (journey_id, modem_index)
);

CREATE TABLE journey_modem_sample (
    journey_id BIGINT NOT NULL,
    round_no INTEGER NOT NULL,
    modem_index INTEGER NOT NULL,
    device_state VARCHAR(40),
    link_state VARCHAR(40),
    rssi INTEGER,
    technology VARCHAR(40),
    operator_id VARCHAR(10),
    cell_id BIGINT,
    PRIMARY KEY (journey_id, round_no, modem_index),
    FOREIGN KEY (journey_id, round_no) REFERENCES journey_sample (journey_id, round_no) ON DELETE CASCADE,
    FOREIGN KEY (journey_id, modem_index) REFERENCES journey_modem (journey_id, modem_index) ON DELETE CASCADE
);

CREATE TABLE journey_playback (
    journey_id BIGINT NOT NULL REFERENCES journey (id) ON DELETE CASCADE,
    playback_health_id BIGINT NOT NULL REFERENCES playback_health (id) ON DELETE CASCADE,
    PRIMARY KEY (journey_id, playback_health_id)
);

CREATE INDEX journey_playback_health_idx ON journey_playback (playback_health_id);
