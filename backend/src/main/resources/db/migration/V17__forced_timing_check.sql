-- Checking the timing of the owner's forced subtitle files against the full English subtitle track inside the film's own
-- media file (expand-only: two new tables and one new nullable column).
--
-- subtitle_sidecar.offset_source says who set offset_ms: NULL = never set (it is 0), OWNER = the owner put it in (a reset
-- to 0 included), AUTO = the timing check set it. The timing check never changes an OWNER offset. An offset that is not 0
-- can only have come from the owner so far, so it is backfilled as OWNER. An old reset to 0 cannot be told from "never
-- set", so any file the owner touched at all (attached by hand, or marked "Looks right") is conservatively OWNER too.
ALTER TABLE subtitle_sidecar ADD COLUMN offset_source VARCHAR(10);
ALTER TABLE subtitle_sidecar ADD CONSTRAINT subtitle_sidecar_offset_source_ck CHECK (offset_source IN ('OWNER', 'AUTO'));
UPDATE subtitle_sidecar SET offset_source = 'OWNER'
WHERE offset_ms <> 0 OR owner_attached OR owner_verified_at IS NOT NULL;

-- embedded_cue_starts: what was read from the full English subtitle track inside one media file, so a film is read once
-- (reading demuxes the whole file: minutes over SMB). fingerprint is the file's size and modification time when read; a
-- changed file is read again. status USABLE: starts_text holds the cue start times in milliseconds as the first start
-- and then the gap to each next one, comma-separated (plain text so the same column works on PostgreSQL and H2; a few
-- thousand cues is a few tens of KB). status NO_REFERENCE: the file has no full English track (reason says why, and
-- subtitle_stream_count how many tracks it has); kept so it is not read again. A read that failed is never stored.
CREATE TABLE embedded_cue_starts (
    media_file_id BIGINT PRIMARY KEY REFERENCES media_file (id) ON DELETE CASCADE,
    fingerprint VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL,
    stream_index INTEGER,
    codec VARCHAR(40),
    subtitle_stream_count INTEGER NOT NULL,
    cue_count INTEGER NOT NULL,
    starts_text TEXT NOT NULL,
    reason VARCHAR(300),
    read_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT embedded_cue_starts_status_ck CHECK (status IN ('USABLE', 'NO_REFERENCE'))
);

-- forced_subtitle_alignment: the result of fitting one sidecar's cue times to the film's own English track. One current
-- row per sidecar. sidecar_identity names the file as stored (its film file, whether it is timed for the whole edition,
-- and a hash of its cues) and reference_key names what it was fitted to (each reference file's id and fingerprint, and
-- where each part starts for a whole-edition file). Neither includes the offset, so applying the fitted offset does not
-- make the row stale. verdict is ALIGNED, CHECK, TOO_FEW or NO_REFERENCE; reasons are plain sentences joined by
-- newlines. fitted_offset_ms is the absolute offset to set (cue times in the file are never changed). applied is true
-- when the check set the sidecar's offset from this result.
CREATE TABLE forced_subtitle_alignment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sidecar_id BIGINT NOT NULL UNIQUE REFERENCES subtitle_sidecar (id) ON DELETE CASCADE,
    sidecar_identity VARCHAR(100) NOT NULL,
    reference_key VARCHAR(1000) NOT NULL,
    verdict VARCHAR(12) NOT NULL,
    fitted_offset_ms INTEGER NOT NULL,
    matched_share DOUBLE PRECISION NOT NULL,
    matched_count INTEGER NOT NULL,
    served_count INTEGER NOT NULL,
    median_residual_ms INTEGER NOT NULL,
    reasons VARCHAR(1000) NOT NULL,
    applied BOOLEAN NOT NULL DEFAULT FALSE,
    checked_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT forced_subtitle_alignment_verdict_ck CHECK (verdict IN ('ALIGNED', 'CHECK', 'TOO_FEW', 'NO_REFERENCE'))
);
