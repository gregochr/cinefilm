-- Library scan (expand-only): how each file was last seen, and how each film was matched.
ALTER TABLE media_file ADD COLUMN modified_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE media_file ADD COLUMN presence VARCHAR(20) NOT NULL DEFAULT 'PRESENT';
ALTER TABLE media_file ADD COLUMN playability VARCHAR(20) NOT NULL DEFAULT 'PLAYABLE';

ALTER TABLE film ADD COLUMN match_status VARCHAR(20) NOT NULL DEFAULT 'MATCHED';
ALTER TABLE film ADD COLUMN match_candidates VARCHAR(8000);

CREATE TABLE scan_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE,
    trigger_source VARCHAR(20) NOT NULL,
    files_seen INTEGER NOT NULL DEFAULT 0,
    new_files INTEGER NOT NULL DEFAULT 0,
    missing_files INTEGER NOT NULL DEFAULT 0,
    error VARCHAR(500)
);

CREATE INDEX idx_media_file_path ON media_file (path);
CREATE INDEX idx_film_tmdb ON film (tmdb_id);
CREATE INDEX idx_person_tmdb ON person (tmdb_id);
