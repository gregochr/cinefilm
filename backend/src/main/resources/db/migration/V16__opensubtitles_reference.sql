-- Checking the owner's forced subtitle files against OpenSubtitles (expand-only: three new tables).
--
-- opensubtitles_reference: a subtitle downloaded from OpenSubtitles as the reference for a film, kept and reused (phases
-- 3 and 4 read it too) so the same file is never downloaded twice for a film and IMDb id (a reference fetched for another IMDb id is never reused). os_file_id is the file id /download took.
-- cues_text is the cues normalised to SRT (at most 1 MB); cue_count 0 means the download could not be read: it is kept
-- (as an unusable reference) so that file id is never fetched again. failed_downloads counts downloads that were charged
-- but gave no usable file; at 3 (or at once for a permanent failure: link refused, too big, no cues) it is final. imdb_id is the IMDb id it was fetched for, so a
-- check made against it stops counting when the film's IMDb id changes.
CREATE TABLE opensubtitles_reference (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    film_id BIGINT NOT NULL REFERENCES film (id) ON DELETE CASCADE,
    imdb_id VARCHAR(16) NOT NULL,
    os_file_id BIGINT NOT NULL,
    release VARCHAR(200),
    cues_text TEXT NOT NULL,
    cue_count INTEGER NOT NULL,
    failed_downloads INTEGER NOT NULL DEFAULT 0,
    fetched_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT opensubtitles_reference_film_file_uq UNIQUE (film_id, imdb_id, os_file_id)
);

-- opensubtitles_budget: the downloads spent per UTC day, so a restart does not hand out a fresh daily allowance.
-- blocked_until is set when OpenSubtitles said the download limit is reached: nothing is downloaded before it.
CREATE TABLE opensubtitles_budget (
    budget_day DATE PRIMARY KEY,
    used INTEGER NOT NULL,
    blocked_until TIMESTAMP WITH TIME ZONE
);

-- forced_subtitle_check: the result of comparing the forced subtitle an edition serves with the OpenSubtitles
-- reference. One current row per edition. served_version names exactly what was compared (the edition's parts and, for each file
-- served, its id, where it starts, its offset and a hash of its cues), so an attach, move, nudge or changed file makes the
-- row stale. verdict is AGREES or CHECK; reasons are plain sentences joined by newlines. An outage is never stored.
CREATE TABLE forced_subtitle_check (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edition_id BIGINT NOT NULL UNIQUE REFERENCES edition (id) ON DELETE CASCADE,
    served_version VARCHAR(1000) NOT NULL,
    reference_id BIGINT NOT NULL REFERENCES opensubtitles_reference (id) ON DELETE CASCADE,
    verdict VARCHAR(10) NOT NULL,
    matched_share DOUBLE PRECISION NOT NULL,
    served_count INTEGER NOT NULL,
    reference_count INTEGER NOT NULL,
    best_offset_ms INTEGER NOT NULL,
    reasons VARCHAR(1000) NOT NULL,
    checked_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX forced_subtitle_check_reference_idx ON forced_subtitle_check (reference_id);
