-- Forced subtitle sidecars (expand-only: one new table). One row per forced English .srt file found beside the films
-- (<stem>.en.forced.srt or <stem>.forced.en.srt), kept in the database so a brief outage of the media share cannot
-- lose the owner's checks.
-- path is relative to the library root. presence is PRESENT or MISSING: a file that is not found is marked MISSING,
-- never deleted. media_file_id is the film file the sidecar belongs to (null = unmatched); it hangs off the file, not
-- the edition, so it follows the file when editions are edited, joined or merged. whole_edition marks a sidecar timed
-- for a whole split edition, stored against part 1. owner_attached stops the scan re-matching a sidecar the owner
-- attached by hand.
-- cues_text is the file's cues normalised to SRT (UTF-8, at most 1 MB of source); parse_report says how it was read.
-- offset_ms is the owner's timing nudge. owner_verified_at is when the owner said it looks right; verified_parts is
-- the comma-joined ids of the edition's part files at that moment, so the check stops counting when the edition's
-- parts change. last_end_ms is the end of the last cue, without the offset.
CREATE TABLE subtitle_sidecar (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path VARCHAR(2000) NOT NULL UNIQUE,
    size_bytes BIGINT NOT NULL,
    modified_at TIMESTAMP WITH TIME ZONE NOT NULL,
    presence VARCHAR(20) NOT NULL,
    media_file_id BIGINT REFERENCES media_file (id),
    whole_edition BOOLEAN NOT NULL DEFAULT FALSE,
    owner_attached BOOLEAN NOT NULL DEFAULT FALSE,
    cues_text TEXT NOT NULL,
    parse_report VARCHAR(2000) NOT NULL,
    cue_count INTEGER NOT NULL DEFAULT 0,
    last_end_ms BIGINT NOT NULL DEFAULT 0,
    offset_ms INTEGER NOT NULL DEFAULT 0,
    owner_verified_at TIMESTAMP WITH TIME ZONE,
    verified_parts VARCHAR(500),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX subtitle_sidecar_media_file_idx ON subtitle_sidecar (media_file_id);
