-- The tables for which train a journey was on (expand-only: two new tables and one column; plan:
-- docs/engineering/journey-data-plan.md, decision 9).
--
-- The train's own feed says which unit the owner was on, not which service. A service's identity and its planned and
-- actual times at each timing point are handed over as a small file, and are stored here once for a train.
--
-- train_run: one service on one date (the timetable's uid and the date are unique), with its headcode and operator.
-- train_run_call: one timing point of a run, in order (seq): planned and actual arrival, departure and pass times.
-- journey.train_run_id: the run a journey was on. Its foreign key is plain on purpose (no cascade, no set-null): a run
-- that a journey points at cannot be deleted, so a mistake is an error and never a silent loss.
CREATE TABLE train_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timetable_uid VARCHAR(10) NOT NULL,
    run_date DATE NOT NULL,
    headcode VARCHAR(10) NOT NULL,
    operator VARCHAR(100),
    source VARCHAR(200),
    imported_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT train_run_uid_date_unique UNIQUE (timetable_uid, run_date)
);

CREATE TABLE train_run_call (
    train_run_id BIGINT NOT NULL REFERENCES train_run (id) ON DELETE CASCADE,
    seq INTEGER NOT NULL,
    location VARCHAR(100) NOT NULL,
    planned_arrival TIMESTAMP WITH TIME ZONE,
    planned_departure TIMESTAMP WITH TIME ZONE,
    planned_pass TIMESTAMP WITH TIME ZONE,
    actual_arrival TIMESTAMP WITH TIME ZONE,
    actual_departure TIMESTAMP WITH TIME ZONE,
    actual_pass TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY (train_run_id, seq)
);

ALTER TABLE journey ADD COLUMN train_run_id BIGINT REFERENCES train_run (id);
CREATE INDEX journey_train_run_idx ON journey (train_run_id);
